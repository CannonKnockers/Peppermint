"""The safety corpus.

Every case is a pair: the command, and the reason it belongs in its list.
The reason is not decoration. When a case fails, the reason tells the next
reader what property broke.

Add a case here whenever a new hole is found. A hole that has a case can
never come back without a red test.
"""

